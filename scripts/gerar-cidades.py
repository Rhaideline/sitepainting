"""Gera lib/cities.ts com as 109 cidades do padrao Wolfs Siding.

Fontes:
  scripts/dados/cidades-wolfs.json  -> lista oficial (slugs) das 109 cidades
  scripts/dados/cidades-atuais.json -> dados ja existentes no site (81 cidades em comum)
  scripts/dados/cidades-novas.json  -> 28 cidades novas (fatos da Wikipedia, censo 2020)
  scripts/dados/coords.json         -> lat/lng da Wikipedia (para "cidades proximas")
Uso: python scripts/gerar-cidades.py
"""
import json, os

D = os.path.join(os.path.dirname(__file__), "dados")
load = lambda f: json.load(open(os.path.join(D, f), encoding="utf-8"))
wolfs = load("cidades-wolfs.json")
atuais = {c["slug"]: c for c in load("cidades-atuais.json")}
novas = {c["slug"]: c for c in load("cidades-novas.json")}
coords = load("coords.json")

out, faltando = [], []
for slug in wolfs:
    c = novas.get(slug) or atuais.get(slug)
    if not c or slug not in coords:
        faltando.append(slug)
        continue
    out.append({
        "slug": slug,
        "name": c["name"],
        "county": c["county"],
        "population": c["population"],
        "region": c["region"],
        "lat": coords[slug]["lat"],
        "lng": coords[slug]["lng"],
        "localFacts": c["localFacts"],
        "challenges": c["paintingChallenges"],
        "homeStyles": c["commonHomeStyles"],
    })
if faltando:
    raise SystemExit(f"faltam dados para: {faltando}")

cab = '''// ============================================
// CITIES (109) - same service area as wolfs-siding.com
// GENERATED by scripts/gerar-cidades.py - edit the JSON sources, not this file.
// Population: 2020 US Census (via Wikipedia). Coordinates: Wikipedia.
// ============================================

export interface City {
  slug: string;
  name: string;
  county: string;
  population: number;
  region: string;
  lat: number;
  lng: number;
  localFacts: string;
  challenges: string[];
  homeStyles: string[];
}

export const cities: City[] = '''
rodape = '''

export const getCity = (slug: string) => cities.find((c) => c.slug === slug);

const toRad = (d: number) => (d * Math.PI) / 180;
/** Straight-line distance in miles between two cities. */
export function milesBetween(a: City, b: City): number {
  const R = 3958.8;
  const dLat = toRad(b.lat - a.lat);
  const dLng = toRad(b.lng - a.lng);
  const h = Math.sin(dLat / 2) ** 2 + Math.cos(toRad(a.lat)) * Math.cos(toRad(b.lat)) * Math.sin(dLng / 2) ** 2;
  return 2 * R * Math.asin(Math.sqrt(h));
}

/** Closest cities by real distance (used for internal links). */
export function nearbyCities(city: City, limit = 8): City[] {
  return cities
    .filter((c) => c.slug !== city.slug)
    .map((c) => ({ c, d: milesBetween(city, c) }))
    .sort((x, y) => x.d - y.d)
    .slice(0, limit)
    .map((x) => x.c);
}

/** Cities grouped by region, regions in a fixed order, towns alphabetical. */
const REGION_ORDER = ["MetroWest", "Central MA", "Route 2 Corridor", "Boston Metro", "North Shore", "South Shore", "Merrimack Valley"];
export const citiesByRegion = (): [string, City[]][] => {
  const groups: Record<string, City[]> = {};
  for (const c of [...cities].sort((a, b) => a.name.localeCompare(b.name))) {
    (groups[c.region] = groups[c.region] || []).push(c);
  }
  return Object.keys(groups)
    .sort((a, b) => (REGION_ORDER.indexOf(a) + 99 * +(REGION_ORDER.indexOf(a) < 0)) - (REGION_ORDER.indexOf(b) + 99 * +(REGION_ORDER.indexOf(b) < 0)))
    .map((r) => [r, groups[r]]);
};
'''
alvo = os.path.join(os.path.dirname(__file__), "..", "lib", "cities.ts")
open(alvo, "w", encoding="utf-8", newline="\n").write(cab + json.dumps(out, ensure_ascii=False, indent=2) + ";" + rodape)
print(len(out), "cidades gravadas em lib/cities.ts")
